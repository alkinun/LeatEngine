@functools.cache
def grid(name: str) -> bytes:
    """The grid of the format of that name: each entry's values, 8 for IQ2's and 4 for IQ3's,
    one byte each."""
    levels, packed = LEVELS[name], bytes.fromhex(_HEX[name])
    bits = 2 if levels == IQ2_LEVELS else 4
    shifts = range(0, 8, bits)
    return bytes(levels[(b >> s) & ((1 << bits) - 1)] for b in packed for s in shifts)
